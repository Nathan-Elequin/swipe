"""Refresh design/buckets-seed.js from data/content-board.json + data/catalog.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
board = json.loads((ROOT / "data" / "content-board.json").read_text(encoding="utf-8"))
catalog = json.loads((ROOT / "data" / "catalog.json").read_text(encoding="utf-8"))
payload = {
    "board": board,
    "catalog": catalog,
    "generated": board.get("updated", ""),
}
text = "// Auto-generated by tools/_write_buckets_seed.py — do not edit by hand.\n"
text += "window.BUCKETS_SEED = " + json.dumps(payload, ensure_ascii=False) + ";\n"
(ROOT / "design" / "buckets-seed.js").write_text(text, encoding="utf-8")
print(f"Wrote buckets-seed.js (board updated {board.get('updated', '?')})")
