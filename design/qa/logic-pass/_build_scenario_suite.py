def story(tid, title, family, items, monsters, face, clicks, expected_text, expected, extra=None):
    its = extra.pop("item_rows", []) if extra else []
    mons = extra.pop("monster_rows", []) if extra else []
    row = {
        "id": tid,
        "title": title,
        "family": family,
        "items": items,
        "monsters": monsters,
        "face": face,
        "challenge": True,
        "clicks": clicks,
        "expected_text": expected_text,
        "expected": expected,
        "cards": [card_ref(x, "item") for x in its] + [card_ref(m, "monster") for m in mons],
    }
    if extra:
        row.update(extra)
    return row


def use(item, auto=True):
    return {"op": "use", "item": item, "auto": auto}


def done():
    return {"op": "done"}


